test.each(["stop", "pause"] as const)("stop playback (%s)", async (button) => {
  // We treat pause as stop for now
  const client = await raop.client({ et: "0" });

  // The idea here is to simulate calling "stop" after the first frame has been sent,
  // i.e. after the first "sleep" has been made. It's a bit tied to implementation
  // details but good enough.
  // NB: Must yield to the event loop (like asyncio.ensure_future in pyatv) and not
  // just to the microtask queue, otherwise the sync packet loop starves everything.
  stubSleep(async () => {
    await client.remoteControl[button]();
    await new Promise<void>((resolve) => setImmediate(resolve));
  });

  await client.stream.streamFile(dataPath("audio_3_packets.wav"));
  expect(raop.state.rawAudio.length).toBeGreaterThanOrEqual(ONE_FRAME_IN_BYTES);
});

