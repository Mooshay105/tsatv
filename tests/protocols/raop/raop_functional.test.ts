test.each([
  ["test", "test"],
  [null, null],
  ["test", null],
] as Array<[string | null, string | null]>)("stream with password server=%p client=%p", async (serverPassword, clientPassword) => {
  raop.usecase.password(serverPassword);

  const conf = raop.conf({ et: "0" });
  const raopService = conf.getService(Protocol.RAOP);
  if (raopService) raopService.password = clientPassword;

  const expectError = serverPassword !== clientPassword;

  const client = await connect(conf);
  raop.track(client);
  let error: unknown = null;
  try {
    await client.stream.streamFile(dataPath("audio_10_frames.wav"));
  } catch (ex) {
    error = ex;
  }
  if (expectError) expect(error).toBeInstanceOf(AuthenticationError);
  else expect(error).toBeNull();
});

