test("push updates", async () => {
  const client = await raop.client({ et: "0" });
  const listener = playingListener(client);
  await client.stream.streamFile(dataPath("only_metadata.wav"));

  // Initial idle + audio playing + back to idle
  await until(() => listener.updates.length === 3);

  let idle = listener.updates[0]!;
  expect(idle.deviceState).toBe(DeviceState.Idle);
  expect(idle.mediaType).toBe(MediaType.Unknown);

  const playing = listener.updates[1]!;
  expect(playing.deviceState).toBe(DeviceState.Playing);
  expect(playing.mediaType).toBe(MediaType.Music);
  expect(playing.artist).toBe("postlund");
  expect(playing.title).toBe("pyatv");
  expect(playing.album).toBe("raop");

  idle = listener.updates[2]!;
  expect(idle.deviceState).toBe(DeviceState.Idle);
  expect(idle.mediaType).toBe(MediaType.Unknown);
});

test("push updates progress", async () => {
  const client = await raop.client({ et: "0" });
  const listener = playingListener(client);
  assertFeaturesInState(client.features.allFeatures(), PROGRESS_FIELDS, FeatureState.Unavailable);

  await client.stream.streamFile(dataPath("static_3sec.ogg"));

  // Initial idle + audio playing + back to idle
  await until(() => listener.updates.length === 3);

  const playing = listener.updates[1]!;
  expect(playing.deviceState).toBe(DeviceState.Playing);
  expect(playing.position).toBe(0);
  expect(playing.totalTime).toBe(3);

  assertFeaturesInState(listener.allFeatures!, PROGRESS_FIELDS, FeatureState.Available);
});

test("metadata features", async () => {
  const client = await raop.client({ et: "0" });
  const listener = playingListener(client);

  // All features should be unavailable when nothing is playing
  assertFeaturesInState(client.features.allFeatures(), METADATA_FIELDS, FeatureState.Unavailable);

  // StreamFile should be available for streaming
  expect(client.features.getFeature(FeatureName.StreamFile).state).toBe(FeatureState.Available);
  await client.stream.streamFile(dataPath("only_metadata.wav"));

  // Use a listener to catch when something starts playing and save that as it's too
  // late to verify when streamFile returns (idle state will be reported).
  await until(() => listener.allFeatures !== null);

  // When playing, everything should be available
  assertFeaturesInState(listener.allFeatures!, METADATA_FIELDS, FeatureState.Available);
});

test("remote control features", async () => {
  const client = await raop.client({ et: "0" });
  const listener = playingListener(client);
  assertFeaturesInState(client.features.allFeatures(), REMOTE_CONTROL_FIELDS, FeatureState.Unavailable);

  // Start playback in the background
  const future = client.stream.streamFile(dataPath("audio_3_packets.wav"));

  // Wait for device to move to playing state and verify feature state
  await listener.playingEvent.wait();
  assertFeaturesInState(client.features.allFeatures(), REMOTE_CONTROL_FIELDS, FeatureState.Available);

  await future;

  // Playback finished so no controls should be available
  assertFeaturesInState(client.features.allFeatures(), REMOTE_CONTROL_FIELDS, FeatureState.Unavailable);
});

