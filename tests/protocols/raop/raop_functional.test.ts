// Used by all sample audio files for now
const CHANNELS = 2;
const SAMPLE_WIDTH = 2; // bytes

// Number of frames per audio packet in RAOP
const FRAMES_PER_PACKET = 352;

const ONE_FRAME_IN_BYTES = FRAMES_PER_PACKET * CHANNELS * SAMPLE_WIDTH;

const METADATA_FIELDS = [FeatureName.Title, FeatureName.Artist, FeatureName.Album];
const PROGRESS_FIELDS = [FeatureName.Position, FeatureName.TotalTime];
const VOLUME_FIELDS = [FeatureName.SetVolume, FeatureName.Volume, FeatureName.VolumeUp, FeatureName.VolumeDown];
const REMOTE_CONTROL_FIELDS = [FeatureName.Stop, FeatureName.Pause];

const isClose = (a: number, b: number) => Math.abs(a - b) <= Math.max(1e-9 * Math.max(Math.abs(a), Math.abs(b)), 0);

const raop = useRaopDevice();

class PlayingListener implements PushListener {
  updates: Playing[] = [];
  allFeatures: Map<FeatureName, FeatureInfo> | null = null;
  readonly playingEvent = new Event();

  constructor(private readonly client: AppleTV) {}

  playstatusUpdate(_updater: unknown, playstatus: Playing): void {
    this.updates.push(playstatus);
    if (playstatus.deviceState === DeviceState.Playing) {
      this.allFeatures = this.client.features.allFeatures();
      this.playingEvent.set();
    }
  }

  playstatusError(_updater: unknown, _exception: Error): void {}
}

function playingListener(client: AppleTV): PlayingListener {
  const listener = new PlayingListener(client);
  client.pushUpdater.listener = listener;
  client.pushUpdater.start();
  return listener;
}

/** Assert that raw audio matches audio generated by audiogen.py. */
async function audioMatches(frames: number, skipFrames = 0, channels = CHANNELS, sampleWidth = SAMPLE_WIDTH): Promise<boolean> {
  let succeeded = true;
  const frameSize = channels * sampleWidth;

  // Wait until there's enough data in the audio buffer for expected number of frames
  await until(() => raop.state.rawAudio.length >= frames * channels * sampleWidth);
  const audio = raop.state.rawAudio;

  // assert per individual frame
  for (let i = 0; i < frames; i++) {
    const actual = audio.subarray(i * frameSize, i * frameSize + frameSize);
    const expected = Buffer.alloc(frameSize, (i + skipFrames) & 0xff);
    if (!actual.equals(expected)) {
      LOGGER.error("%s != %s for frame %d", actual, expected, i + skipFrames);
      succeeded = false;
    }
  }
  return succeeded;
}

function assertFeaturesInState(allFeatures: Map<FeatureName, FeatureInfo>, features: FeatureName[], state: FeatureState): void {
  for (const feature of features) expect(allFeatures.get(feature)!.state).toBe(state);
}

