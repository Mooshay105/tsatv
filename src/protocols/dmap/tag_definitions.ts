/** Look up a tag based on its key. Returns a DmapTag. */
export function lookupTag(name: string): DmapTag {
  return Object.prototype.hasOwnProperty.call(TAGS, name) ? TAGS[name]! : new DmapTag(readUnknown, "unknown tag");
}
